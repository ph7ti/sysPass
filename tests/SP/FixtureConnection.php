namespace SP\Tests;

use PDO;

/**
 * Minimal database fixture helper. Replaces the removed PHPUnit DbUnit
 * connection object, which is only used by the test suite to count rows.
 *
 * @package SP\Tests
 */
final class FixtureConnection
{
    /**
     * @var PDO
     */
    private $pdo;

    /**
     * @param PDO $pdo
     */
    public function __construct(PDO $pdo)
    {
        $this->pdo = $pdo;
    }

    /**
     * @param string $table
     *
     * @return int
     */
    public function getRowCount($table): int
    {
        return (int)$this->pdo
            ->query(sprintf('SELECT COUNT(*) FROM `%s`', $table))
            ->fetchColumn();
    }
}
